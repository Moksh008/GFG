def seed_reference_data(db: Session) -> None:
    """Insert providers that are missing and refresh the directory fields of existing ones."""
    existing = {d.name: d for d in db.scalars(select(Doctor))}
    added = 0
    for spec in DOCTORS:
        doc = existing.get(spec["name"])
        if doc is None:
            db.add(Doctor(**spec))
            added += 1
        else:
            for k, v in spec.items():
                setattr(doc, k, v)
    db.commit()
    if added:
        log.info("Seeded %d providers", added)


