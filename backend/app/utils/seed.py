def _demo_scans(db: Session, user: User, now: datetime) -> None:
    for area, spec in _SCANS.items():
        diags = []
        for days_ago, url, sev, red, cm2, border, sym, status, result, notes, conf in spec:
            ts = now - timedelta(days=days_ago, hours=3)
            img = SkinImage(user_id=user.id, storage_path=url, quality={"score": 90, "acceptable": True, "warnings": []},
                            created_at=ts)
            db.add(img)
            db.flush()
            probs = {"eczema": conf, "normal": round((1 - conf) * 0.5, 4), "psoriasis": round((1 - conf) * 0.4, 4),
                     "vitiligo": round((1 - conf) * 0.1, 4)}
            d = SkinDiagnosis(
                user_id=user.id, image_id=img.id, body_area=area, notes=notes,
                predicted_label="eczema", confidence=conf, probabilities=probs, model_version="demo-data",
                severity_score=sev, redness_index=red, area_cm2=cm2, border_regularity=border, symmetry=sym,
                status=status, ai_result=result,
                ai_summary=f"Pattern consistent with eczema; severity {sev}/100. " + skin_knowledge.info("eczema")["care"][0],
                questionnaire=skin_knowledge.questionnaire("eczema"), created_at=ts,
            )
            db.add(d)
            db.flush()
            diags.append(d)
        for prev, cur in zip(diags, diags[1:]):
            delta = cur.severity_score - prev.severity_score
            db.add(ImprovementRecord(
                user_id=user.id, baseline_diagnosis_id=prev.id, current_diagnosis_id=cur.id, body_area=area,
                days_between=round((cur.created_at - prev.created_at).total_seconds() / 86400, 1), severity_delta=delta,
                redness_delta=cur.redness_index - prev.redness_index, area_delta_cm2=round(cur.area_cm2 - prev.area_cm2, 2),
                improvement_pct=round(-delta / prev.severity_score * 100, 1), trend="improving",
                analysis=(f"Your {area} shows improvement: severity fell {abs(delta)} points, redness dropped "
                          f"{prev.redness_index - cur.redness_index}% and the affected area contracted by about "
                          f"{prev.area_cm2 - cur.area_cm2:.1f} cm². Keep following your current routine."),
                details={}, created_at=cur.created_at,
            ))


def populate_demo_data(db: Session, user: User) -> None:
    """Fill an account with a realistic month of history so every dashboard widget has data."""
    now = datetime.now(timezone.utc)
    user.full_name = user.full_name or "Alex Mercer"
    user.date_of_birth = user.date_of_birth or "1998-04-12"
    user.skin_type = user.skin_type or "Fitzpatrick III"
    user.primary_condition = user.primary_condition or "Eczema"
    user.known_triggers = user.known_triggers or ["stress", "sweat", "dry weather"]
    user.medical_history = user.medical_history or "Atopic dermatitis since childhood; seasonal allergic rhinitis."
    if user.latitude is None:
        user.latitude, user.longitude = 28.6139, 77.2090

    _demo_scans(db, user, now)

    # --- mood logs: stress tapering as skin improves ------------------------
    rng = random.Random(42)
    emotions_hi = [["stressed", "anxious"], ["frustrated", "tired"], ["embarrassed", "stressed"], ["overwhelmed"]]
    emotions_lo = [["calm"], ["hopeful", "relaxed"], ["content"], ["relieved", "calm"]]
    # 40 days so the oldest (30-day) scan also has a full week of preceding mood data; day 0 = today.
    for day in range(40, -1, -1):
        if day and rng.random() < 0.15:
            continue
        progress = max(0.0, (30 - day) / 30)
        stress = max(1, min(10, round(8 - 5 * progress + rng.uniform(-1.2, 1.2))))
        mood = max(1, min(10, round(4 + 4.5 * progress + rng.uniform(-1, 1))))
        db.add(MoodLog(
            user_id=user.id, mood_score=mood, stress_level=stress,
            sleep_hours=round(5.5 + 2 * progress + rng.uniform(-0.7, 0.7), 1),
            itch_level=max(0, min(10, round(7 - 6 * progress + rng.uniform(-1, 1)))),
            emotions=rng.choice(emotions_hi if stress >= 6 else emotions_lo),
            triggers=rng.choice([["work deadline"], ["sweat"], ["poor sleep"], []]) if stress >= 6 else [],
            logged_at=now - timedelta(days=day, hours=rng.randint(0, 4) if day else 0),
        ))

    # --- medications + two weeks of adherence history ------------------------
    started = now - timedelta(days=30)
    meds = [
        Medicine(user_id=user.id, name="Tacrolimus Ointment 0.1%", dosage="Thin layer", timing="Morning & Night",
                 frequency="2x Daily", doses_per_day=2, area=f"{FOREARM} & {NECK}", refill_date="2026-12-14",
                 created_at=started),
        Medicine(user_id=user.id, name="Desonide Cream 0.05%", dosage="Pea-sized amount", timing="Night",
                 frequency="1x Daily", doses_per_day=1, area=NECK, refill_date="2027-01-05", created_at=started),
        Medicine(user_id=user.id, name="Cetirizine HCl 10mg", dosage="1 tablet (oral)", timing="Evening",
                 frequency="1x Daily", doses_per_day=1, area="Systemic antihistamine", refill_date="2026-12-28",
                 created_at=started),
    ]
    db.add_all(meds)
    db.flush()
    today = today_utc()
    for m in meds:
        for back in range(1, 14):
            r = rng.random()
            if r < 0.8:
                db.add(DoseLog(medicine_id=m.id, day=today - timedelta(days=back), doses_taken=m.doses_per_day))
            elif r < 0.9 and m.doses_per_day > 1:
                db.add(DoseLog(medicine_id=m.id, day=today - timedelta(days=back), doses_taken=1))
    db.add(DoseLog(medicine_id=meds[0].id, day=today, doses_taken=2))
    db.add(DoseLog(medicine_id=meds[2].id, day=today, doses_taken=1))

    # --- care plan ------------------------------------------------------------
    steps = [
        ("Exercise", "Sweat-Trigger Barrier Care", "Active days", "Recommended",
         ["Rinse within 15 min after cardio workouts", "Apply ceramide barrier cream"]),
        ("Nutrition", "Anti-Inflammatory Protocol", "Continuous", "Ongoing",
         ["Omega-3 2000mg + Evening Primrose", "Maintain hydration > 2.5L/day"]),
        ("Testing", "Patch Allergen Series 40", "Next week", "Scheduled",
         ["Avoid topical corticosteroids 48 hrs prior", "Clinic A - Room 302"]),
        ("Assessment", f"Follow-up scan of {NECK}", "This week", "Due",
         ["Capture a clear shot in natural daylight", "Use the same angle as last time"]),
    ]
    for i, (cat, title, rng_txt, status, bullets) in enumerate(steps):
        db.add(CareStep(user_id=user.id, category=cat, title=title, date_range=rng_txt, status=status, bullets=bullets,
                        created_at=now - timedelta(minutes=10 * (len(steps) - i))))

    # --- appointments: one past visit, one upcoming ----------------------------
    db.flush()
    raman = db.scalars(select(Doctor).where(Doctor.name.like("Dr. Priya Raman%"))).first()
    if raman:
        past = (datetime.now() - timedelta(days=12)).replace(hour=11, minute=30, second=0, microsecond=0)
        db.add(Appointment(user_id=user.id, doctor_id=raman.id, doctor_name=raman.name, slot=past.strftime(SLOT_FORMAT),
                           department=raman.department, type="Video consultation", report_attached=True,
                           notes="Stress-linked flares; discussed sleep routine."))
    jenkins = db.scalars(select(Doctor).where(Doctor.name.like("Dr. Sarah Jenkins%"))).first()
    if jenkins:
        free = open_slots(jenkins, booked_slots(db, [jenkins.id]).get(jenkins.id))
        later = [s for s in free if parse_slot(s) >= datetime.now() + timedelta(days=2)] or free
        if later:
            db.add(Appointment(user_id=user.id, doctor_id=jenkins.id, doctor_name=jenkins.name, slot=later[0],
                               department=jenkins.department, type="In-person visit", report_attached=True,
                               notes="Review forearm progress and neck patch."))
    db.commit()
    log.info("Filled demo data for user %s", user.id)
