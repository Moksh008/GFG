def seed_demo_user(db: Session) -> None:
    """Create the (empty) demo login. Its data is filled on demand via POST /demo/seed."""
    if db.scalars(select(User).where(User.email == settings.demo_email)).first():
        return
    user = User(email=settings.demo_email, hashed_password=hash_password(settings.demo_password), full_name="Alex Mercer")
    db.add(user)
    db.flush()
    seed_new_user(db, user)
    db.commit()
    log.info("Created demo account %s (no data; use 'Fill demo data' in the app)", settings.demo_email)


def has_health_data(db: Session, user: User) -> bool:
    return any(
        db.scalars(select(model.id).where(model.user_id == user.id).limit(1)).first() is not None
        for model in (SkinDiagnosis, MoodLog, Medicine, Appointment)
    )


def clear_user_data(db: Session, user: User) -> None:
    """Remove a user's health records (scans, mood, meds, care plan, appointments, Aria chat)."""
    uid = user.id
    med_ids = list(db.scalars(select(Medicine.id).where(Medicine.user_id == uid)))
    if med_ids:
        db.execute(delete(DoseLog).where(DoseLog.medicine_id.in_(med_ids)))
    db.execute(delete(ImprovementRecord).where(ImprovementRecord.user_id == uid))
    db.execute(delete(SkinDiagnosis).where(SkinDiagnosis.user_id == uid))
    for img in db.scalars(select(SkinImage).where(SkinImage.user_id == uid)):
        if not img.storage_path.startswith(("http://", "https://")):
            delete_image(img.storage_path)
    for model in (SkinImage, MoodLog, Medicine, CareStep, Appointment, ChatMessage):
        db.execute(delete(model).where(model.user_id == uid))
    db.commit()


