import jsPDF from 'jspdf';

export function generateDoctorReport({ patientName = 'Alex Mercer', scans = [], medicines = [], doctor = 'Dr. Sarah Jenkins, MD' }) {
  const doc = new jsPDF({
    unit: 'pt',
    format: 'a4'
  });

  const primaryColor = [31, 42, 46];
  const tealColor = [31, 106, 102];
  const mutedColor = [138, 154, 160];

  // Header Banner
  doc.setFillColor(15, 59, 63);
  doc.rect(0, 0, 595, 80, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text('DermaTrack™ Clinical Summary Report', 40, 42);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text('CONFIDENTIAL MEDICAL DOSSIER • GENERATED FOR CLINICAL CONSULTATION', 40, 60);

  // Patient & Clinical Meta
  doc.setTextColor(...primaryColor);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.text('Patient & Provider Overview', 40, 115);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`Patient Name: ${patientName}`, 40, 135);
  doc.text(`DOB / ID: Jan 14, 1992 • #DT-88219`, 40, 150);
  doc.text(`Target Lesion / Area: Right Forearm (Epithelial)`, 40, 165);

  doc.text(`Attending Specialist: ${doctor}`, 320, 135);
  doc.text(`Report Date: ${new Date().toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })}`, 320, 150);
  doc.text(`Adherence Index: 88% (Excellent)`, 320, 165);

  doc.setDrawColor(220, 230, 235);
  doc.line(40, 180, 555, 180);

  // Section: Longitudinal Scan Evolution
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...tealColor);
  doc.text('1. Longitudinal Lesion Progression (AI-Assisted Metrics)', 40, 205);

  let yPos = 230;
  scans.forEach((scan, index) => {
    doc.setFillColor(index === 0 ? 240 : 248, index === 0 ? 248 : 250, index === 0 ? 245 : 252);
    doc.roundedRect(40, yPos - 12, 515, 48, 6, 6, 'F');
    doc.setDrawColor(210, 225, 228);
    doc.roundedRect(40, yPos - 12, 515, 48, 6, 6, 'D');

    doc.setFontSize(10);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(...primaryColor);
    doc.text(`${scan.date} (${scan.relativeTime}) - ${scan.status}`, 55, yPos + 6);

    doc.setFont('helvetica', 'normal');
    doc.setTextColor(80, 90, 95);
    doc.text(`Classification: ${scan.aiResult}`, 55, yPos + 22);

    doc.text(`Redness: ${scan.rednessIndex}%`, 330, yPos + 6);
    doc.text(`Lesion Area: ${scan.areaCm2} cm²`, 330, yPos + 22);
    doc.text(`Symmetry: ${scan.symmetry}`, 440, yPos + 6);
    doc.text(`Severity: ${scan.severityScore}/100`, 440, yPos + 22);

    yPos += 58;
  });

  // Section: Active Treatment & Medication Adherence
  yPos += 15;
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...tealColor);
  doc.text('2. Active Medical Regimen & Adherence', 40, yPos);

  yPos += 25;
  medicines.forEach((med) => {
    doc.setFontSize(10);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(...primaryColor);
    doc.text(`• ${med.name} (${med.dosage})`, 50, yPos);

    doc.setFont('helvetica', 'normal');
    doc.setTextColor(...mutedColor);
    doc.text(`Schedule: ${med.frequency} (${med.timing}) | Area: ${med.area} | Refill: ${med.refillDate}`, 65, yPos + 14);

    yPos += 30;
  });

  // Legal & Clinical Disclaimer
  yPos = 720;
  doc.setFillColor(245, 248, 250);
  doc.roundedRect(40, yPos, 515, 60, 4, 4, 'F');
  doc.setDrawColor(200, 215, 220);
  doc.roundedRect(40, yPos, 515, 60, 4, 4, 'D');

  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(200, 70, 70);
  doc.text('CLINICAL & STATUTORY DISCLAIMER (HIPAA / GDPR / AI OBSERVATION STANDARD):', 50, yPos + 18);

  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 115, 120);
  const disclaimerText = 'DermaTrack AI results represent probabilistic biometric observations and algorithmic surface analysis, NOT definitive clinical diagnoses. All observations must be confirmed by a licensed medical practitioner. Patient health data is end-to-end encrypted in compliance with healthcare data protection standards.';
  doc.text(doc.splitTextToSize(disclaimerText, 495), 50, yPos + 32);

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(...mutedColor);
  doc.text('Generated by DermaTrack AI Assistant (Aria Core v2.4) • Verified Medical Export', 40, 810);
  doc.text('Page 1 of 1', 520, 810);

  doc.save(`DermaTrack_Clinical_Report_${patientName.replace(/\s+/g, '_')}_Nov2026.pdf`);
}
